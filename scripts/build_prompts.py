#!/usr/bin/env python3
"""Build image-generation prompts from a character design JSON file.

Usage:
    python3 scripts/build_prompts.py characters/ayesha/ayesha.json
    python3 scripts/build_prompts.py characters/ayesha/ayesha.json --format json

Writes a Markdown (default) or JSON prompt sheet to stdout containing:
  * an identity block shared by every prompt (keeps the face consistent)
  * a portrait reference prompt and a full-body reference prompt
  * one portrait prompt per facial expression
  * the negative prompt
"""
import argparse
import json
import sys


def _lower_first(text: str) -> str:
    return text[:1].lower() + text[1:] if text else text


def _article(text: str) -> str:
    """Return 'an' for words read with a leading vowel sound (incl. '11', '8')."""
    return "an" if text[:1].lower() in "aeiou8" or text.startswith(("11", "18")) else "a"


def with_article(text: str) -> str:
    return f"{_article(text)} {text}"


def identity_block(c: dict) -> str:
    f = c["face_features"]
    eyes, brows, nose, lips = f["eyes"], f["eyebrows"], f["nose"], f["lips"]
    skin = c["skin"]
    hh = c["hair_and_hijab"]
    cl = c["clothing"]
    body = c["body_features"]

    parts = [
        f"{c['age']}-year-old {c['nationality']} girl named {c['name']}",
        f"{_lower_first(f['face_shape'])}, {_lower_first(f['face_structure'])}",
        f"{_lower_first(f['forehead'])}",
        f"{_lower_first(eyes['shape'])} {_lower_first(eyes['size'])} "
        f"{_lower_first(eyes['color'])} eyes with {_lower_first(eyes['eyelashes'])}",
        f"{_lower_first(brows['shape'])} {_lower_first(brows['thickness'])} "
        f"{_lower_first(brows['color'])} eyebrows",
        f"{_lower_first(nose['shape'])} {_lower_first(nose['proportion'])} nose",
        f"{_lower_first(lips['shape'])} {_lower_first(lips['size'])} lips in "
        f"{_lower_first(lips['color'])}",
        f"{_lower_first(f['cheeks'])}, {_lower_first(f['chin'])}, "
        f"{_lower_first(f['jawline'])}",
        f"{_lower_first(skin['tone'])}, {_lower_first(skin['texture'])} with "
        f"{_lower_first(skin['details'])}, {_lower_first(skin['finish'])} skin finish",
        f"wearing a {_lower_first(hh['hijab_color'])} "
        f"{_lower_first(hh['hijab'])} with {_lower_first(hh['coverage'])}, "
        f"hair {_lower_first(hh['hair'])}",
        f"dressed in a {_lower_first(cl['color'])} "
        f"{_lower_first(cl['outfit'])}: {_lower_first(cl['shirt'])} and "
        f"{_lower_first(cl['shalwar'])}, {_lower_first(cl['fabric'])} fabric, "
        f"{_lower_first(cl['style'])}",
        f"{_lower_first(body['build'])} build, {_lower_first(body['proportions'])}",
    ]
    return ", ".join(parts)


def render_suffix(c: dict) -> str:
    r = c["rendering_settings"]
    return ", ".join(
        [
            _lower_first(r["quality"]),
            _lower_first(r["render_style"]),
            _lower_first(r["lighting"]),
            f"shot on {_lower_first(r['camera'])}",
            _lower_first(r["skin_details"]),
            _lower_first(r["anatomy"]),
            f"{r['resolution']} resolution",
        ]
    )


def build(c: dict) -> dict:
    ident = identity_block(c)
    suffix = render_suffix(c)
    body = c["body_features"]
    gaze = _lower_first(c["face_features"]["eyes"]["expression"])

    prompts = {
        "portrait_reference": (
            f"Head-and-shoulders portrait of {with_article(ident)}, {gaze}, "
            f"facing camera, neutral plain background, {suffix}"
        ),
        "full_body_reference": (
            f"Full-body standing reference photo of {with_article(ident)}, "
            f"{_lower_first(body['posture'])}, {_lower_first(body['hands'])} visible, "
            f"head to feet in frame, neutral plain background, {suffix}"
        ),
    }
    expressions = {
        expr: f"Close-up portrait of {with_article(ident)}, {_lower_first(expr)}, "
        f"neutral plain background, {suffix}"
        for expr in c.get("facial_expressions", [])
    }
    locked = [
        k.removeprefix("fixed_").replace("_", " ")
        for k, v in c.get("identity_consistency", {}).items()
        if v
    ]
    return {
        "character_id": c["character_id"],
        "name": c["name"],
        "identity_block": ident,
        "prompts": prompts,
        "expressions": expressions,
        "negative_prompt": ", ".join(c.get("negative_prompt", [])),
        "locked_traits": locked,
    }


def to_markdown(out: dict) -> str:
    lines = [
        f"# {out['name']} — Prompt Sheet (`{out['character_id']}`)",
        "",
        "_Generated by `scripts/build_prompts.py` — edit the JSON, not this file._",
        "",
        "## Identity block",
        "",
        "Reuse this verbatim in every prompt to keep the character consistent.",
        "",
        "```text",
        out["identity_block"],
        "```",
        "",
        "## Reference shots",
        "",
    ]
    for key, text in out["prompts"].items():
        lines += [f"### {key.replace('_', ' ').title()}", "", "```text", text, "```", ""]
    lines += ["## Facial expressions", ""]
    for expr, text in out["expressions"].items():
        lines += [f"### {expr}", "", "```text", text, "```", ""]
    lines += [
        "## Negative prompt",
        "",
        "```text",
        out["negative_prompt"],
        "```",
        "",
        "## Locked identity traits",
        "",
        "Keep these unchanged across every generation (use the same seed / a",
        "face reference image where your generator supports it):",
        "",
    ]
    lines += [f"- {t}" for t in out["locked_traits"]]
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("character_json")
    ap.add_argument("--format", choices=["markdown", "json"], default="markdown")
    args = ap.parse_args()

    with open(args.character_json, encoding="utf-8") as fh:
        character = json.load(fh)
    out = build(character)
    if args.format == "json":
        json.dump(out, sys.stdout, indent=2, ensure_ascii=False)
        sys.stdout.write("\n")
    else:
        sys.stdout.write(to_markdown(out))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
